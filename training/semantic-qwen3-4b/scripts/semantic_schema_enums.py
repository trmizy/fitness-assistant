"""
Loads the REAL enum arrays from datasets/semantic_schema_enums.json, which
is generated by backend/services/ai-service/src/scripts/
export-semantic-schema-enums.ts directly from schema.ts - never hand-
duplicated (the task's own rule). Run that script again after any
schema.ts enum change:
  cd backend/services/ai-service && npx tsx src/scripts/export-semantic-schema-enums.ts
"""
import json
from pathlib import Path

_ENUMS_PATH = Path(__file__).resolve().parents[1] / "datasets" / "semantic_schema_enums.json"
if not _ENUMS_PATH.exists():
    raise SystemExit(
        f"{_ENUMS_PATH} not found. Run: cd backend/services/ai-service && "
        f"npx tsx src/scripts/export-semantic-schema-enums.ts"
    )
_enums = json.loads(_ENUMS_PATH.read_text(encoding="utf-8"))

ENTITY_TYPES = set(_enums["ENTITY_TYPES"])
GOALS = set(_enums["GOALS"])
PRIMARY_INTENTS = set(_enums["PRIMARY_INTENTS"])
WORKFLOW_INTENTS = set(_enums["WORKFLOW_INTENTS"])
REQUESTED_ACTIONS = set(_enums["REQUESTED_ACTIONS"])
REFERENCE_KINDS = set(_enums["REFERENCE_KINDS"])
CORRECTION_FIELDS = set(_enums["CORRECTION_FIELDS"])
NEGATION_TARGETS = set(_enums["NEGATION_TARGETS"])
SCHEMA_EXPORTED_AT = _enums["exportedAt"]

# The canonical v1 category set (task §5). "Full coverage" checks (v1 only)
# are against exactly this set.
V1_CATEGORIES = {
    "INTENT", "ENTITY", "CORRECTION", "REFERENCE", "FOLLOWUP_SLOT", "REVISION",
    "AMBIGUITY_UNKNOWN", "MULTI_INTENT", "FITNESS_SHORTHAND", "SAFETY_NON_AUTHORITY",
}
# Every category any dataset file (v0 or v1) may legally use. v0's starter
# set predates the v1 naming and used "AMBIGUITY"/"SHORTHAND" - kept valid
# here (so v0 still parses) but excluded from V1_CATEGORIES's full-coverage
# check.
CATEGORIES = V1_CATEGORIES | {"AMBIGUITY", "SHORTHAND"}
