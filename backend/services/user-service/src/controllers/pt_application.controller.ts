import { Response } from "express";
import path from "path";
import fs from "fs";
import { AuthRequest } from "../middleware/auth.middleware";
import { ptApplicationService } from "../services/pt_application.service";
import {
  signPtApplicationDocumentUrls,
  verifyDocumentS3Key,
  verifyDocumentUrl,
} from "../utils/ptDocumentUrl.util";
import { logger } from "@gym-coach/shared";
import { ptTermsService } from "../services/pt-terms.service";
import { auditMeta } from "../services/audit.service";
import { profileRepository } from "../repositories/profile.repository";
import { clientErrorMessage } from "../utils/db-error.util";
import { errorCodeBody } from "../utils/error-code.util";
import { PTApplicationStatus } from "../generated/prisma";
import {
  createPresignedGetObject,
  createPtApplicationDocumentUploadUrl,
  isOwnPtApplicationDocumentKey,
  ptApplicationDocumentUrlForKey,
} from "../services/s3-upload.service";

const INVALID_INPUT = "Dữ liệu gửi lên không hợp lệ. Vui lòng kiểm tra lại các trường đã nhập.";

const PT_APPLICATION_STATUSES = Object.values(PTApplicationStatus) as string[];
function isPtApplicationStatus(value: unknown): boolean {
  return typeof value === "string" && PT_APPLICATION_STATUSES.includes(value);
}

// Only plain filenames (as generated by multer: fieldname-timestamp-random.ext)
// are ever accepted — rejects path traversal (`..`, `/`) outright.
const SAFE_FILENAME_RE = /^[a-zA-Z0-9_.-]+$/;
const UPLOADS_DIR = path.join(process.cwd(), "uploads", "pt-applications");

export const ptApplicationController = {
  /** D25 - the current PT terms text + this user's standing (accepted / must re-confirm). Any signed-in user. */
  async getTerms(req: AuthRequest, res: Response) {
    try {
      const profile = await profileRepository.findByUserId(req.user!.id);
      return res.json(await ptTermsService.getForUser(req.user!.id, profile?.isPT === true));
    } catch (error: any) {
      logger.error(error, "Get PT terms error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  /** D25 - confirm the CURRENT version (idempotent). An old/unknown version is 409 with the current one. */
  async acceptTerms(req: AuthRequest, res: Response) {
    try {
      const version = typeof req.body?.version === "string" ? req.body.version : undefined;
      const profile = await profileRepository.findByUserId(req.user!.id);
      // An approved PT re-confirming; anyone else here is an applicant confirming ahead of submitting.
      const source = profile?.isPT === true ? "RECONFIRM" : "APPLICATION";
      return res.json(await ptTermsService.accept(req.user!.id, version, source, auditMeta(req)));
    } catch (error: any) {
      logger.error(error, "Accept PT terms error");
      if (error?.status && typeof error.code === "string") {
        return res.status(error.status).json({ error: error.message, code: error.code, termsVersion: error.termsVersion });
      }
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  async getMe(req: AuthRequest, res: Response) {
    try {
      const app = await ptApplicationService.getMe(req.user!.id);
      return res.json(app);
    } catch (error: any) {
      logger.error(error, "Get my PT application error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  async saveDraft(req: AuthRequest, res: Response) {
    try {
      const app = await ptApplicationService.saveDraft(req.user!.id, req.body);
      return res.json(app);
    } catch (error: any) {
      logger.error(error, "Save PT application draft error");
      return res.status(400).json({ error: clientErrorMessage(error, INVALID_INPUT) });
    }
  },

  async submit(req: AuthRequest, res: Response) {
    try {
      const termsVersion = typeof req.body?.termsVersion === "string" ? req.body.termsVersion : undefined;
      const app = await ptApplicationService.submit(req.user!.id, { termsVersion, meta: auditMeta(req) });
      return res.json(app);
    } catch (error: any) {
      logger.error(error, "Submit PT application error");
      if (typeof error?.code === "string" && error.code.startsWith("PT_TERMS_") && error.status) {
        return res.status(error.status).json({ error: error.message, code: error.code, termsVersion: error.termsVersion });
      }
      return res.status(400).json({ error: clientErrorMessage(error, INVALID_INPUT) });
    }
  },

  async upload(req: AuthRequest, res: Response) {
    try {
      if (!req.file) {
        return res.status(400).json({ error: "No file uploaded" });
      }
      // `url` is the STABLE, canonical reference the frontend stores in form
      // state and round-trips through saveDraft — it is deliberately never
      // itself a signed/expiring link (see pt_application.repository.ts's
      // upsertDraft, which canonicalizes any signed link the client might
      // echo back anyway, so this is defense in depth, not the only guard).
      // `previewUrl` is a short-lived signed link the browser can actually
      // load via a plain <img src> right after upload (no static file
      // serving of this directory exists anymore — see app.ts).
      const url = `/uploads/pt-applications/${req.file.filename}`;
      return res.json({
        url,
        previewUrl: signPtApplicationDocumentUrls({ portraitPhotoUrl: url })
          .portraitPhotoUrl,
        filename: req.file.originalname,
      });
    } catch (error: any) {
      logger.error(error, "PT application upload error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  async presignUpload(req: AuthRequest, res: Response) {
    try {
      const contentType = req.body?.contentType;
      if (typeof contentType !== "string" || !contentType) {
        return res.status(400).json({ error: "contentType is required" });
      }
      const target = await createPtApplicationDocumentUploadUrl(
        req.user!.id,
        contentType,
      );
      return res.json(target);
    } catch (error: any) {
      if (error?.status) {
        return res.status(error.status).json({ error: error.message, ...errorCodeBody(error) });
      }
      logger.error(error, "PT application presign upload error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  async confirmUpload(req: AuthRequest, res: Response) {
    try {
      const key = req.body?.key;
      if (typeof key !== "string" || !key) {
        return res.status(400).json({ error: "key is required" });
      }
      if (!isOwnPtApplicationDocumentKey(req.user!.id, key)) {
        return res.status(403).json({ error: "key does not belong to this user" });
      }
      const url = ptApplicationDocumentUrlForKey(key);
      return res.json({
        key,
        url,
        previewUrl: signPtApplicationDocumentUrls({ portraitPhotoUrl: url })
          .portraitPhotoUrl,
      });
    } catch (error: any) {
      if (error?.status) {
        return res.status(error.status).json({ error: error.message });
      }
      logger.error(error, "PT application confirm upload error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  /**
   * Serves a PT application document. Requires no Authorization header (a
   * plain <img src=...> works) — authorization is proven by the request's
   * `exp`/`sig` query params, which are only ever handed out by getMe/
   * getById/listApplications/adminReviewAction (all of which already run
   * behind authMiddleware + the existing own-application/ADMIN-only route
   * gates). See ptDocumentUrl.util.ts's doc comment for the full rationale.
   */
  async getDocument(req: AuthRequest, res: Response) {
    const { filename } = req.params;
    const { exp, sig } = req.query;

    if (!SAFE_FILENAME_RE.test(filename)) {
      return res.status(400).json({ error: "Invalid filename" });
    }
    if (!verifyDocumentUrl(filename, exp as string | undefined, sig as string | undefined)) {
      return res.status(403).json({ error: "Invalid or expired link" });
    }

    const filePath = path.join(UPLOADS_DIR, filename);
    // Defense in depth against path.join surprises: the resolved path must
    // still live inside UPLOADS_DIR.
    if (!filePath.startsWith(UPLOADS_DIR + path.sep) && filePath !== UPLOADS_DIR) {
      return res.status(400).json({ error: "Invalid filename" });
    }
    if (!fs.existsSync(filePath)) {
      return res.status(404).json({ error: "Not found" });
    }
    return res.sendFile(filePath);
  },

  async getS3Document(req: AuthRequest, res: Response) {
    const key = typeof req.query.key === "string" ? req.query.key : "";
    const exp = req.query.exp as string | undefined;
    const sig = req.query.sig as string | undefined;

    if (!verifyDocumentS3Key(key, exp, sig)) {
      return res.status(403).json({ error: "Invalid or expired link" });
    }

    try {
      const url = await createPresignedGetObject({ key });
      return res.redirect(302, url);
    } catch (error: any) {
      if (error?.status) {
        return res.status(error.status).json({ error: error.message });
      }
      logger.error(error, "PT application S3 document redirect error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  // Admin endpoints
  async listApplications(req: AuthRequest, res: Response) {
    try {
      // B02: an unknown ?status used to reach Prisma, which rejects a bad enum value with a 500.
      // A key that is present but not exactly one valid status (NEEDS_INFO, lowercase, empty, repeated)
      // is the caller's mistake: 400 + a machine code. An absent key still means "no filter".
      const rawStatus = req.query.status;
      if (rawStatus !== undefined && !isPtApplicationStatus(rawStatus)) {
        return res.status(400).json({
          error: `Trạng thái lọc không hợp lệ. Giá trị hợp lệ: ${PT_APPLICATION_STATUSES.join(", ")}.`,
          code: "INVALID_STATUS_FILTER",
        });
      }
      const apps = await ptApplicationService.listApplications(req.query);
      const mapped = apps.map((app: any) => ({
        ...app,
        user: {
          firstName: app.userProfile?.firstName,
          lastName: app.userProfile?.lastName,
          email: app.userProfile?.email || "N/A", // Fallback if email not in profile
        },
      }));
      return res.json(mapped);
    } catch (error: any) {
      logger.error(error, "List PT applications error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  async getById(req: AuthRequest, res: Response) {
    try {
      const app: any = await ptApplicationService.getById(req.params.id);
      if (!app) return res.status(404).json({ error: "Application not found" });

      const mapped = {
        ...app,
        user: {
          firstName: app.userProfile?.firstName,
          lastName: app.userProfile?.lastName,
          email: app.userProfile?.email || "N/A",
        },
      };
      return res.json(mapped);
    } catch (error: any) {
      logger.error(error, "Get PT application by ID error");
      return res.status(500).json({ error: "Internal server error" });
    }
  },

  async reviewAction(req: AuthRequest, res: Response) {
    try {
      const { action } = req.params;
      const app = await ptApplicationService.adminReviewAction(
        req.params.id,
        action as any,
        req.body,
        req.user!.id,
      );
      return res.json(app);
    } catch (error: any) {
      logger.error(error, "Admin review action error");
      return res.status(400).json({ error: clientErrorMessage(error, INVALID_INPUT) });
    }
  },
};
