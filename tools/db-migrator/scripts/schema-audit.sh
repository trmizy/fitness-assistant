#!/usr/bin/env bash
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=./lib.sh
source "$DIR/lib.sh"

log "=== SCHEMA AUDIT (reads Aurora; writes only to a disposable local shadow Postgres) ==="

require_env AWS_REGION
derive_db_base
ensure_dumps_downloaded

GEN_DIR=/work/generated
REPORT_DIR=/work/reports
REPORT="$REPORT_DIR/schema-drift-report.md"
MASTER_PREPATCH="$GEN_DIR/schema-prepatch.sql"
ENUM_EVIDENCE="$GEN_DIR/enum-data-drift.tsv"
: > "$ENUM_EVIDENCE"

SHADOW_DATA=/work/shadow-data
SHADOW_PORT=5433
# TCP loopback, not a Unix socket: Prisma's migrate-diff connector does not
# honor libpq's `?host=/path` unix-socket convention (verified locally — it
# tries to resolve the socket directory's basename as a TCP hostname and
# fails). 127.0.0.1-only avoids that entirely and never leaves the container.

mkdir -p "$GEN_DIR" "$REPORT_DIR" "$SHADOW_DATA"
chown -R postgres:postgres "$SHADOW_DATA"

shadow_url_for() { echo "postgresql://postgres@127.0.0.1:${SHADOW_PORT}/${1}"; }

log "--- bootstrapping local shadow Postgres (replays repo migrations only; never touches Aurora) ---"
if [ ! -f "$SHADOW_DATA/PG_VERSION" ]; then
  gosu postgres initdb -D "$SHADOW_DATA" --auth=trust --no-locale --encoding=UTF8 \
    > "$GEN_DIR/shadow-initdb.log" 2>&1
fi
# pg_ctl's -l logfile is opened by the postgres OS user (post-gosu), not by this
# shell — it must live under a postgres-writable path, unlike the initdb
# redirection above (which this root shell opens itself before gosu runs).
gosu postgres pg_ctl -D "$SHADOW_DATA" \
  -o "-p ${SHADOW_PORT} -c listen_addresses=127.0.0.1" \
  -w -l "$SHADOW_DATA/server.log" start

cleanup_shadow() {
  gosu postgres pg_ctl -D "$SHADOW_DATA" -m fast -w stop >/dev/null 2>&1 || true
}
trap cleanup_shadow EXIT

{
  echo "-- Generated by tools/db-migrator schema-audit.sh"
  echo "-- Timestamp (UTC): $(date -u +%FT%TZ)"
  echo "--"
  echo "-- This file concatenates the per-database patches below for human review."
  echo "-- apply-prepatch.sh applies the per-database files (schema-prepatch.<db>.sql),"
  echo "-- NOT this concatenation, because each section must run against a different"
  echo "-- Aurora database."
  echo
} > "$MASTER_PREPATCH"

{
  echo "# Schema Drift Report"
  echo
  echo "Generated (UTC): $(date -u +%FT%TZ)"
  echo
  echo "Method: \`prisma migrate diff\` from the live Aurora schema (\`--from-url\`) to the"
  echo "repo's checked-in Prisma migrations (\`--to-migrations\`), computed via a disposable"
  echo "local shadow Postgres that only ever replays repo migration.sql files. No column"
  echo "type is ever guessed — every type comes straight from the migration that created it."
  echo
  echo "| Database | Service | Audit status | Safe (auto-patched) | Needs manual review |"
  echo "|---|---|---|---|---|"
} > "$REPORT"

OVERALL_NEEDS_REVIEW=0

for entry in "${DB_MANIFEST[@]}"; do
  IFS='|' read -r dbname dumpfile svc <<< "$entry"
  log "--- auditing ${dbname} (${svc}) ---"

  migrations_dir="/work/migrations/${svc}/migrations"
  shadow_db="shadow_${svc//-/_}"
  raw_diff="$GEN_DIR/raw-diff.${dbname}.sql"
  safe_patch="$GEN_DIR/schema-prepatch.${dbname}.sql"
  unsafe_notes="$GEN_DIR/needs-review.${dbname}.sql"

  : > "$unsafe_notes"

  gosu postgres createdb -h 127.0.0.1 -p "$SHADOW_PORT" "$shadow_db" 2>/dev/null || true

  status="OK"
  if ! prisma migrate diff \
        --from-url "$(prisma_db_url_for "$dbname")" \
        --to-migrations "$migrations_dir" \
        --shadow-database-url "$(shadow_url_for "$shadow_db")" \
        --script > "$raw_diff" 2> "$GEN_DIR/raw-diff.${dbname}.stderr.log"; then
    status="AUDIT_FAILED"
    echo "ERROR: prisma migrate diff failed for ${dbname}; see generated/raw-diff.${dbname}.stderr.log" >&2
  fi

  safe_count=0
  unsafe_count=0

  if [ "$status" = "OK" ]; then
    {
      echo "-- ===== DATABASE: ${dbname} (service: ${svc}) ====="
      echo "-- Safe to re-run: every statement below is CREATE ... IF NOT EXISTS,"
      echo "-- ADD COLUMN IF NOT EXISTS, or a duplicate_object-guarded CREATE TYPE."
      echo
    } > "$safe_patch"

    awk -f "$DIR/classify-diff.awk" -v db="$dbname" \
      -v safe_out="$safe_patch" -v unsafe_out="$unsafe_notes" "$raw_diff"

    # Schema-level diffing (above) only catches enum values the CURRENT
    # migrations define but Aurora is missing. It can't catch a value that's
    # only in the dump's historical DATA and isn't in any current migration
    # either — exactly what broke `fitness_assistant_user` restore
    # ("WORKOUT_UPCOMING"). Cross-check literal dump content against Aurora's
    # live enum as a second, independent pass.
    "$DIR/enum-data-audit.sh" "$dbname" "/work/dumps/${dumpfile}" \
      "$(shadow_url_for "$shadow_db")" "$safe_patch" "$ENUM_EVIDENCE"

    # grep -c prints a single "0" but EXITS 1 when there are zero matches in
    # an existing file. Two failed fix attempts here, for the record:
    #   - `cmd || echo 0` doubles the output to "0\n0" (grep's own "0" plus
    #     the fallback), which then broke the `-gt 0` integer test below.
    #   - dropping the fallback entirely means `safe_count=$(grep -c ...)`
    #     itself exits 1 under `set -e` whenever a database has zero drift,
    #     killing the whole script (confirmed on ECS: it died mid-way through
    #     fitness_assistant_payment, which turned out to have no drift at all).
    # `|| true` inside the substitution neutralizes the exit code without
    # adding any output of its own.
    safe_count=$(grep -c '^-- \[' "$safe_patch" || true)
    unsafe_count=$(grep -c '^-- \[' "$unsafe_notes" || true)

    cat "$safe_patch" >> "$MASTER_PREPATCH"
    echo >> "$MASTER_PREPATCH"
  else
    : > "$safe_patch"
  fi

  if [ "$unsafe_count" -gt 0 ] || [ "$status" != "OK" ]; then
    OVERALL_NEEDS_REVIEW=1
  fi

  echo "| ${dbname} | ${svc} | ${status} | ${safe_count} | ${unsafe_count} |" >> "$REPORT"
done

{
  echo
  echo "## Enum data drift (from actual dump content, not just schema diffing)"
  echo
  echo "Method: for every enum-typed column the real migrations define (read from"
  echo "the shadow Postgres, so this covers brand-new tables too), the matching"
  echo "table's literal \`COPY\` data is extracted directly from that database's"
  echo "\`.dump\` file with \`pg_restore -t <table> -f -\` (no database touched, no"
  echo "value ever guessed) and every distinct value found is compared against"
  echo "Aurora's live \`pg_enum\`. This catches values used in old row data that"
  echo "aren't in any current migration — schema-only diffing can't see those,"
  echo "and it is exactly what broke \`fitness_assistant_user\` restore before"
  echo "(\`WORKOUT_UPCOMING\`). All statements below are already included in"
  echo "\`generated/schema-prepatch.<db>.sql\` as \`ADD VALUE IF NOT EXISTS\`."
  echo
  if [ -s "$ENUM_EVIDENCE" ]; then
    echo "| Database | Enum type | Missing value(s) | Evidence (table.column) |"
    echo "|---|---|---|---|"
    cat "$ENUM_EVIDENCE"
  else
    echo "_None. Every enum value found in the 7 dumps already exists in Aurora's_"
    echo "_live enums._"
  fi
  echo

  echo "## Needs-manual-review detail"
  echo
  any_unsafe=0
  for entry in "${DB_MANIFEST[@]}"; do
    IFS='|' read -r dbname dumpfile svc <<< "$entry"
    f="$GEN_DIR/needs-review.${dbname}.sql"
    if [ -s "$f" ]; then
      any_unsafe=1
      echo "### ${dbname}"
      echo
      echo '```sql'
      cat "$f"
      echo '```'
      echo
    fi
  done
  if [ "$any_unsafe" -eq 0 ]; then
    echo "_None. Every detected difference was an additive, idempotent-safe statement._"
    echo
  fi
  echo "## How to apply"
  echo
  echo "1. Review this report and \`generated/schema-prepatch.sql\`."
  echo "2. If any database is listed above under \"Needs-manual-review detail\", resolve it"
  echo "   manually first (confirm the real source-of-truth column/table shape) — the"
  echo "   prepatch intentionally excludes those statements."
  echo "3. Run \`MODE=apply-prepatch\` to apply the safe, idempotent patch to Aurora."
} >> "$REPORT"

OUT_PREFIX="$(migrator_output_prefix)"
log "--- publishing generated/ and reports/ to ${OUT_PREFIX} (next stages read from here) ---"
aws s3 cp "$GEN_DIR" "${OUT_PREFIX}/generated/" --recursive --only-show-errors --region "$AWS_REGION"
aws s3 cp "$REPORT_DIR" "${OUT_PREFIX}/reports/" --recursive --only-show-errors --region "$AWS_REGION"

if [ "$OVERALL_NEEDS_REVIEW" -eq 1 ]; then
  log "=== SCHEMA AUDIT DONE — one or more databases need manual review: ${REPORT} ==="
else
  log "=== SCHEMA AUDIT DONE — all detected drift is safely auto-patchable: ${REPORT} ==="
fi
