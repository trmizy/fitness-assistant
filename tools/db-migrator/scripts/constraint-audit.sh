#!/usr/bin/env bash
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=./lib.sh
source "$DIR/lib.sh"

log "=== CONSTRAINT AUDIT (read-only: no constraint applied, no data changed) ==="

require_env AWS_REGION
derive_db_base

GEN_DIR=/work/generated
REPORT_DIR=/work/reports
REPORT="$REPORT_DIR/constraint-audit-report.md"
SAFE_MASTER="$GEN_DIR/safe-constraints.sql"
BLOCKED_MASTER="$GEN_DIR/blocked-constraints.sql"
ROWS_FILE="$GEN_DIR/constraint-audit-rows.tmp"
ORPHAN_LIST="$GEN_DIR/constraint-audit-orphans.tmp"
mkdir -p "$GEN_DIR" "$REPORT_DIR"

OUT_PREFIX="$(migrator_output_prefix)"
log "--- fetching needs-review files from ${OUT_PREFIX}/generated/ ---"
# Always fetched fresh from S3: each MODE is its own ephemeral task.
aws s3 cp "${OUT_PREFIX}/generated/" "$GEN_DIR/" --recursive \
  --exclude "*" --include "needs-review.*.sql" \
  --only-show-errors --region "$AWS_REGION"

: > "$ROWS_FILE"
: > "$ORPHAN_LIST"
{
  echo "-- Generated by tools/db-migrator constraint-audit.sh"
  echo "-- Timestamp (UTC): $(date -u +%FT%TZ)"
  echo "--"
  echo "-- ONLY statements the audit PROVED safe against live Aurora data:"
  echo "--   * ADD FOREIGN KEY with orphan count = 0"
  echo "--   * ALTER TYPE ADD VALUE not yet present in pg_enum"
  echo "-- Nothing in this file has ever been executed. There is no apply mode."
  echo
} > "$SAFE_MASTER"
{
  echo "-- Generated by tools/db-migrator constraint-audit.sh"
  echo "-- Timestamp (UTC): $(date -u +%FT%TZ)"
  echo "--"
  echo "-- BLOCKED (orphan rows / invalid reference) and MANUAL (destructive or"
  echo "-- unsupported) items. Do NOT execute anything here without resolving the"
  echo "-- reason documented above each statement. Nothing here has been executed."
  echo
} > "$BLOCKED_MASTER"

SAFE_FK=0; BLOCKED=0; SAFE_ENUM=0; MANUAL=0; INVALID=0; ALREADY=0

# All helpers query the CURRENT $dbname (set by the loop below).
q() { psql "$(db_url_for "$dbname")" -v ON_ERROR_STOP=1 -Atqc "$1"; }
table_exists() { [ "$(q "select count(*) from information_schema.tables where table_schema='public' and table_name='$1';")" = "1" ]; }
col_exists()   { [ "$(q "select count(*) from information_schema.columns where table_schema='public' and table_name='$1' and column_name='$2';")" = "1" ]; }
fk_exists()    { [ "$(q "select count(*) from information_schema.table_constraints where constraint_schema='public' and table_name='$1' and constraint_name='$2' and constraint_type='FOREIGN KEY';")" = "1" ]; }
enum_type_exists()  { [ "$(q "select count(*) from pg_type where typname='$1' and typtype='e';")" = "1" ]; }
enum_value_exists() { [ "$(q "select count(*) from pg_enum e join pg_type t on t.oid=e.enumtypid where t.typname='$1' and e.enumlabel='$2';")" = "1" ]; }

fk_regex="^ALTER[[:space:]]+TABLE[[:space:]]+\"([A-Za-z0-9_]+)\"[[:space:]]+ADD[[:space:]]+CONSTRAINT[[:space:]]+\"([A-Za-z0-9_]+)\"[[:space:]]+FOREIGN[[:space:]]+KEY[[:space:]]*\(([^)]+)\)[[:space:]]+REFERENCES[[:space:]]+\"([A-Za-z0-9_]+)\"[[:space:]]*\(([^)]+)\)"
enum_regex="^ALTER[[:space:]]+TYPE[[:space:]]+\"([A-Za-z0-9_]+)\"[[:space:]]+ADD[[:space:]]+VALUE[[:space:]]+'([^']*)'"
notnull_regex="^ALTER[[:space:]]+TABLE[[:space:]]+\"([A-Za-z0-9_]+)\"[[:space:]]+ALTER[[:space:]]+COLUMN[[:space:]]+\"([A-Za-z0-9_]+)\"[[:space:]]+SET[[:space:]]+NOT[[:space:]]+NULL"

row() { # db type name path total nonnull orphan status reason
  printf '| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n' "$@" >> "$ROWS_FILE"
}

for entry in "${DB_MANIFEST[@]}"; do
  IFS='|' read -r dbname dumpfile svc <<< "$entry"
  nr="$GEN_DIR/needs-review.${dbname}.sql"
  if [ ! -s "$nr" ]; then
    log "--- ${dbname}: no needs-review statements ---"
    : > "$GEN_DIR/safe-constraints.${dbname}.sql"
    : > "$GEN_DIR/blocked-constraints.${dbname}.sql"
    continue
  fi
  log "--- constraint-audit: ${dbname} ---"

  stmts_file="$GEN_DIR/statements.${dbname}.tmp"
  awk -f "$DIR/split-statements.awk" "$nr" > "$stmts_file"

  safe_db="$GEN_DIR/safe-constraints.${dbname}.sql"
  blocked_db="$GEN_DIR/blocked-constraints.${dbname}.sql"
  echo "-- [${dbname}] audit-proven safe statements only" > "$safe_db"
  echo "-- [${dbname}] blocked / manual statements — NOT safe to execute as-is" > "$blocked_db"

  while IFS= read -r stmt; do
    [ -z "$stmt" ] && continue

    if [[ "$stmt" =~ $fk_regex ]]; then
      child="${BASH_REMATCH[1]}"; cname="${BASH_REMATCH[2]}"
      ccols_raw="${BASH_REMATCH[3]}"; parent="${BASH_REMATCH[4]}"; pcols_raw="${BASH_REMATCH[5]}"

      child_cols=(); parent_cols=()
      IFS=',' read -ra tmp <<< "$ccols_raw"
      for c in "${tmp[@]}"; do c="${c//\"/}"; c="${c// /}"; child_cols+=("$c"); done
      IFS=',' read -ra tmp <<< "$pcols_raw"
      for c in "${tmp[@]}"; do c="${c//\"/}"; c="${c// /}"; parent_cols+=("$c"); done
      ccols_disp=$(IFS=,; echo "${child_cols[*]}")
      pcols_disp=$(IFS=,; echo "${parent_cols[*]}")
      path="${child}(${ccols_disp}) → ${parent}(${pcols_disp})"

      total=0; nonnull=0; orphan=0; status=""; reason=""

      if [ "${#child_cols[@]}" -ne "${#parent_cols[@]}" ]; then
        status="INVALID_REFERENCE"; reason="column count mismatch between child and parent key"
      elif ! table_exists "$child"; then
        status="INVALID_REFERENCE"; reason="child table ${child} does not exist on Aurora"
      elif ! table_exists "$parent"; then
        status="INVALID_REFERENCE"; reason="parent table ${parent} does not exist on Aurora"
      else
        missing=""
        for c in "${child_cols[@]}";  do col_exists "$child"  "$c" || missing="${missing} ${child}.${c}"; done
        for c in "${parent_cols[@]}"; do col_exists "$parent" "$c" || missing="${missing} ${parent}.${c}"; done
        if [ -n "$missing" ]; then
          status="INVALID_REFERENCE"; reason="column(s) missing:${missing}"
        elif fk_exists "$child" "$cname"; then
          status="ALREADY_APPLIED"; reason="constraint already exists on Aurora"
        else
          # PostgreSQL default FK semantics (MATCH SIMPLE): a row is only
          # checked when EVERY key column is non-null; any NULL column means
          # the row is unconstrained.
          notnull_pred=""; join_pred=""; i=0
          for c in "${child_cols[@]}"; do
            notnull_pred+="${notnull_pred:+ AND }c.\"${c}\" IS NOT NULL"
            join_pred+="${join_pred:+ AND }p.\"${parent_cols[$i]}\" = c.\"${c}\""
            i=$((i+1))
          done
          total=$(q "select count(*) from public.\"${child}\";")
          nonnull=$(q "select count(*) from public.\"${child}\" c where ${notnull_pred};")
          orphan=$(q "select count(*) from public.\"${child}\" c where ${notnull_pred} and not exists (select 1 from public.\"${parent}\" p where ${join_pred});")
          if [ "$orphan" = "0" ]; then
            status="SAFE_FK"; reason="0 orphans; safe to add (validates ${nonnull} non-null rows)"
          else
            status="BLOCKED_ORPHANS"; reason="${orphan} orphan row(s); fix or remove them before adding this FK"
          fi
        fi
      fi

      row "$dbname" "AddForeignKey" "\`${cname}\`" "$path" "$total" "$nonnull" "$orphan" "$status" "$reason"

      case "$status" in
        SAFE_FK)
          SAFE_FK=$((SAFE_FK+1))
          { echo "-- [${dbname}] SAFE_FK: ${child}(${ccols_disp}) -> ${parent}(${pcols_disp}), orphans=0"; echo "$stmt"; echo; } >> "$safe_db" ;;
        BLOCKED_ORPHANS)
          BLOCKED=$((BLOCKED+1))
          if col_exists "$child" "id"; then
            sel='c."id"::text'
          else
            parts=(); for c in "${child_cols[@]}"; do parts+=("c.\"${c}\"::text"); done
            sel="concat_ws(',', $(IFS=,; echo "${parts[*]}"))"
          fi
          examples=$(q "select ${sel} from public.\"${child}\" c where ${notnull_pred} and not exists (select 1 from public.\"${parent}\" p where ${join_pred}) limit 20;" | paste -sd, -)
          echo "| ${dbname} | \`${cname}\` | ${path} | ${orphan} | ${examples} |" >> "$ORPHAN_LIST"
          { echo "-- [${dbname}] BLOCKED_ORPHANS: ${orphan} orphan row(s) in ${child}(${ccols_disp}) with no ${parent}(${pcols_disp})"
            echo "-- Sample child keys (max 20): ${examples}"
            echo "-- ${stmt}"; echo; } >> "$blocked_db" ;;
        INVALID_REFERENCE)
          INVALID=$((INVALID+1))
          { echo "-- [${dbname}] INVALID_REFERENCE: ${reason}"; echo "-- ${stmt}"; echo; } >> "$blocked_db" ;;
        ALREADY_APPLIED) ALREADY=$((ALREADY+1)) ;;
      esac

    elif [[ "$stmt" =~ $enum_regex ]]; then
      etype="${BASH_REMATCH[1]}"; evalue="${BASH_REMATCH[2]}"
      if ! enum_type_exists "$etype"; then
        status="INVALID_REFERENCE"; reason="enum type ${etype} does not exist on Aurora"
      elif enum_value_exists "$etype" "$evalue"; then
        status="ALREADY_APPLIED"; reason="value '${evalue}' already in pg_enum"
      else
        status="SAFE_ENUM_ADD"; reason="value '${evalue}' not in pg_enum; additive"
      fi
      row "$dbname" "AlterEnum" "\`${etype}\` + '${evalue}'" "—" "—" "—" "—" "$status" "$reason"
      case "$status" in
        SAFE_ENUM_ADD)
          SAFE_ENUM=$((SAFE_ENUM+1))
          { echo "-- [${dbname}] SAFE_ENUM_ADD: ${etype} + '${evalue}'"
            echo "ALTER TYPE \"${etype}\" ADD VALUE IF NOT EXISTS '${evalue//\'/\'\'}';"; echo; } >> "$safe_db" ;;
        INVALID_REFERENCE)
          INVALID=$((INVALID+1))
          { echo "-- [${dbname}] INVALID_REFERENCE: ${reason}"; echo "-- ${stmt}"; echo; } >> "$blocked_db" ;;
        ALREADY_APPLIED) ALREADY=$((ALREADY+1)) ;;
      esac

    elif [[ "$stmt" =~ $notnull_regex ]]; then
      # SET NOT NULL is destructive if any row is currently NULL there — never
      # auto-applied — but the feasibility question (how many NULLs exist right
      # now) is a plain read-only COUNT, so we answer it instead of leaving the
      # reviewer to go find out by hand.
      ncTable="${BASH_REMATCH[1]}"; ncCol="${BASH_REMATCH[2]}"
      MANUAL=$((MANUAL+1))
      if ! table_exists "$ncTable"; then
        row "$dbname" "AlterTable(SET NOT NULL)" "\`${ncTable}.${ncCol}\`" "—" "—" "—" "—" "MANUAL" "table ${ncTable} does not exist on Aurora"
        { echo "-- [${dbname}] MANUAL: table ${ncTable} does not exist"; echo "-- ${stmt}"; echo; } >> "$blocked_db"
      elif ! col_exists "$ncTable" "$ncCol"; then
        row "$dbname" "AlterTable(SET NOT NULL)" "\`${ncTable}.${ncCol}\`" "—" "—" "—" "—" "MANUAL" "column ${ncTable}.${ncCol} does not exist on Aurora"
        { echo "-- [${dbname}] MANUAL: column ${ncTable}.${ncCol} does not exist"; echo "-- ${stmt}"; echo; } >> "$blocked_db"
      else
        ncTotal=$(q "select count(*) from public.\"${ncTable}\";")
        ncNulls=$(q "select count(*) from public.\"${ncTable}\" where \"${ncCol}\" IS NULL;")
        ncNonNull=$((ncTotal - ncNulls))
        if [ "$ncNulls" = "0" ]; then
          ncReason="0 NULL rows out of ${ncTotal} — SET NOT NULL would succeed today, but still MANUAL by design (narrows a column, not additive)"
        else
          ncReason="${ncNulls} row(s) currently NULL — SET NOT NULL would FAIL today; backfill or leave nullable"
        fi
        row "$dbname" "AlterTable(SET NOT NULL)" "\`${ncTable}.${ncCol}\`" "—" "$ncTotal" "$ncNonNull" "$ncNulls" "MANUAL" "$ncReason"
        { echo "-- [${dbname}] MANUAL: ${ncReason}"; echo "-- ${stmt}"; echo; } >> "$blocked_db"
      fi

    else
      # DropIndex / DropForeignKey / rename / drop column / anything else not
      # explicitly recognized: never analyzed further, never executed.
      MANUAL=$((MANUAL+1))
      short="${stmt:0:110}"
      row "$dbname" "Manual" "—" "—" "—" "—" "—" "MANUAL" "destructive/unsupported, human review only: \`${short}\`"
      { echo "-- [${dbname}] MANUAL: destructive or unsupported statement, human review required"
        echo "-- ${stmt}"; echo; } >> "$blocked_db"
    fi
  done < "$stmts_file"

  cat "$safe_db" >> "$SAFE_MASTER"; echo >> "$SAFE_MASTER"
  cat "$blocked_db" >> "$BLOCKED_MASTER"; echo >> "$BLOCKED_MASTER"
  rm -f "$stmts_file"
done

{
  echo "# Constraint Audit Report"
  echo
  echo "Generated (UTC): $(date -u +%FT%TZ)"
  echo
  echo "**Read-only audit.** No constraint was added, no data was changed, nothing in"
  echo "\`generated/safe-constraints*.sql\` has been executed. Every count comes from a"
  echo "live query against Aurora. FK orphan check uses PostgreSQL's default \`MATCH SIMPLE\`"
  echo "semantics: a row is only checked when **all** key columns are non-null."
  echo
  echo "## Summary"
  echo
  echo "| Status | Count |"
  echo "|---|---|"
  echo "| SAFE_FK | ${SAFE_FK} |"
  echo "| BLOCKED_ORPHANS | ${BLOCKED} |"
  echo "| SAFE_ENUM_ADD | ${SAFE_ENUM} |"
  echo "| ALREADY_APPLIED | ${ALREADY} |"
  echo "| MANUAL | ${MANUAL} |"
  echo "| INVALID_REFERENCE | ${INVALID} |"
  echo
  echo "## Findings"
  echo
  echo "| Database | Statement type | Constraint / enum | Child → Parent | Total rows | Non-null rows | Orphan count | Status | Recommendation |"
  echo "|---|---|---|---|---|---|---|---|---|"
  cat "$ROWS_FILE"
  echo
  echo "## Orphan foreign keys"
  echo
  if [ -s "$ORPHAN_LIST" ]; then
    echo "| Database | Constraint | Child → Parent | Orphan count | Sample child keys (max 20) |"
    echo "|---|---|---|---|---|"
    cat "$ORPHAN_LIST"
  else
    echo "_None. Every audited foreign key has zero orphan rows._"
  fi
  echo
  echo "## Outputs"
  echo
  echo "- \`generated/safe-constraints.sql\` (+ \`safe-constraints.<db>.sql\`): only SAFE_FK and SAFE_ENUM_ADD."
  echo "- \`generated/blocked-constraints.sql\` (+ per-db): BLOCKED_ORPHANS, INVALID_REFERENCE, MANUAL, with reasons."
} > "$REPORT"

rm -f "$ROWS_FILE" "$ORPHAN_LIST"

log "--- publishing to ${OUT_PREFIX} ---"
aws s3 cp "$REPORT" "${OUT_PREFIX}/reports/constraint-audit-report.md" --only-show-errors --region "$AWS_REGION"
for f in "$SAFE_MASTER" "$BLOCKED_MASTER" "$GEN_DIR"/safe-constraints.*.sql "$GEN_DIR"/blocked-constraints.*.sql; do
  [ -f "$f" ] && aws s3 cp "$f" "${OUT_PREFIX}/generated/$(basename "$f")" --only-show-errors --region "$AWS_REGION"
done

log "SUMMARY SAFE_FK=${SAFE_FK} BLOCKED_ORPHANS=${BLOCKED} SAFE_ENUM_ADD=${SAFE_ENUM} ALREADY_APPLIED=${ALREADY} MANUAL=${MANUAL} INVALID_REFERENCE=${INVALID}"
log "=== CONSTRAINT AUDIT DONE (nothing applied) ==="
